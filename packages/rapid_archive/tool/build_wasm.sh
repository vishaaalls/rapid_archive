#!/usr/bin/env bash
# Builds the Rust core for the browser and embeds it in the Dart package
# (lib/src/wasm_bytes.g.dart), so web apps need no extra asset setup.
# Needs: rustup target add wasm32-unknown-unknown, and clang is NOT required
# (the web build uses zlib-rs, which is pure Rust).
set -euo pipefail
cd "$(dirname "$0")/.."
cargo build --release --target wasm32-unknown-unknown --manifest-path native/Cargo.toml
wasm=native/target/wasm32-unknown-unknown/release/rapid_archive.wasm
if command -v wasm-opt >/dev/null; then wasm-opt -O3 "$wasm" -o "$wasm"; fi
{
  echo "// GENERATED by tool/build_wasm.sh from native/. Do not edit."
  echo "// $(wc -c < "$wasm" | tr -d ' ') bytes of WebAssembly, base64-encoded."
  echo "const String rapidArchiveWasmBase64 ="
  base64 < "$wasm" | tr -d '\n' | fold -w 76 | sed "s/.*/    '&'/"
  echo "    ;"
} > lib/src/wasm_bytes.g.dart
echo "wrote lib/src/wasm_bytes.g.dart ($(wc -c < "$wasm") byte wasm)"
